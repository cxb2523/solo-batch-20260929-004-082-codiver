public class CodeMetricsDemo {
  public String describe(int mode) {
    String result = "default";
    if (mode == 1) { result = "one"; }
    else if (mode == 2) { result = "two"; }
    else if (mode == 3) { result = "three"; }
    else if (mode == 4) { result = "four"; }
    else if (mode == 5) { result = "five"; }
    else if (mode == 6) { result = "six"; }
    else if (mode == 7) { result = "seven"; }
    else if (mode == 8) { result = "eight"; }
    else if (mode == 9) { result = "nine"; }
    return result;
  }
}
